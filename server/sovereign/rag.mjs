export function buildSystemPrompt(hits) {
  const context = hits.map(h => h.content).join('\n\n')
  if (!context) {
    return RULES + `

동해 자료집.
지금 질문과 맞는 자료집 항목이 없다. 아직 가진 자료가 없어 답을 드리기 어렵다고 친절하게 말하고 다른 것을 물어보라고 한 문장 덧붙인다. 없는 사실은 지어내지 않는다.`
  }
  return RULES + `

동해 자료집. 아래 사실만 근거로 삼는다.
${context}

위 자료집 문장을 그대로 옮기지 말고 친절한 존댓말 대화체로 다시 말해라. 확인 안 됨이라고 적힌 항목은 답변에서 빼라.`
}
